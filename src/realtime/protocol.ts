import { z } from 'zod';

// ---- Client → server -------------------------------------------------------------------

export const clientMessage = z.discriminatedUnion('type', [
  z.object({
    type: z.literal('subscribe'),
    conversationId: z.uuid(),
    /** Highest sequence number the client already has; 0 for "nothing yet". */
    lastSeq: z.number().int().min(0).default(0),
  }),
  z.object({ type: z.literal('unsubscribe'), conversationId: z.uuid() }),
  z.object({ type: z.literal('ping') }),
]);

export type ClientMessage = z.infer<typeof clientMessage>;

// ---- Server → client -------------------------------------------------------------------

/** A message as sent to clients. A deleted message keeps its seq but loses its body. */
export type MessageView = {
  id: string;
  conversationId: string;
  seq: number;
  senderId: string;
  body: string | null;
  editedAt: string | null;
  deletedAt: string | null;
  createdAt: string;
};

export type NotificationView = {
  id: string;
  type: 'NEW_MESSAGE' | 'ADDED_TO_CONVERSATION';
  conversationId: string | null;
  messageId: string | null;
  preview: string;
  readAt: string | null;
  createdAt: string;
};

/** Events that travel through Redis pub/sub and are forwarded to sockets as-is. */
export type RealtimeEvent =
  | { type: 'message.created'; message: MessageView }
  | { type: 'message.updated'; message: MessageView }
  | { type: 'message.deleted'; message: MessageView }
  | { type: 'notification.created'; notification: NotificationView };

/** Events generated by the gateway for one socket only. */
export type GatewayEvent =
  | { type: 'replay.done'; conversationId: string; lastSeq: number }
  | { type: 'replay.truncated'; conversationId: string; fromSeq: number; latestSeq: number }
  | { type: 'pong' }
  | { type: 'error'; message: string; details?: unknown };

export type ServerEvent = RealtimeEvent | GatewayEvent;

export const conversationChannel = (conversationId: string) => `conv:${conversationId}`;
export const userChannel = (userId: string) => `user:${userId}`;
